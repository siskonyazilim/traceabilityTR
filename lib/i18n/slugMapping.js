/**
 * Resolves a potentially localized slug back to its base (English) slug.
 * @param {'blog'|'solution'|'catalogSolution'|'catalogProduct'|'portfolio'} type
 * @param {string} slug
 * @returns {string}
 */
export function resolveSlug(type, slug) {
  if (!slug) return '';
  const typeMappings = slugMappings[type];
  if (!typeMappings) return slug;

  for (const [baseSlug, translations] of Object.entries(typeMappings)) {
    if (
      translations.tr === slug ||
      translations.en === slug ||
      translations.ro === slug ||
      baseSlug === slug
    ) {
      return baseSlug;
    }
  }

  return slug;
}

/**
 * Returns the localized slug for a given base slug and locale.
 * @param {'blog'|'solution'|'catalogSolution'|'catalogProduct'|'portfolio'} type
 * @param {string} baseSlug
 * @param {'tr'|'en'|'ro'} locale
 * @returns {string}
 */
export function getLocalizedSlug(type, baseSlug, locale) {
  if (!baseSlug) return '';
  const typeMappings = slugMappings[type];
  if (!typeMappings) return baseSlug;

  const resolvedBase = resolveSlug(type, baseSlug);
  const translations = typeMappings[resolvedBase];
  if (!translations) return resolvedBase;

  return translations[locale] || resolvedBase;
}
